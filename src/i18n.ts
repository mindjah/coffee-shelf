const DICTS: Record<Lang, Dict> = { en, ru }

export const LANG_NAMES: Record<Lang, string> = { en: 'English', ru: 'Русский' }

export function resolveLang(pref: string): Lang {
  if (pref === 'en' || pref === 'ru') return pref
  const device = (navigator.languages?.[0] ?? navigator.language ?? 'en').toLowerCase()
  return device.startsWith('ru') ? 'ru' : 'en'
}

export function useLang(): Lang {
  return resolveLang(useSettings().lang)
}

export function useT(): Dict {
  return DICTS[useLang()]
}

/** Explanation text for a recommender reason; `short` drops "than you usually drink". */
export function reasonText(t: Dict, r: Pick<Reason, 'id' | 'up'>, lang: Lang, short = false): string {
  if (r.id.startsWith('country:')) {
    const code = r.id.slice('country:'.length)
    const name = countryName({ country: code, countryCodes: [code] }, lang)
    return r.up ? name : t.notFromCountry(name)
  }
  const pair = t.reasons[short && r.id === 'roast' ? 'roastShort' : r.id]
  return pair ? pair[r.up ? 0 : 1] : r.id
}

const regionNames = new Map<Lang, Intl.DisplayNames>()

export function countryName(c: Pick<Coffee, 'country' | 'countryCodes'>, lang: Lang): string {
  if (!c.countryCodes?.length) return c.country
  let names = regionNames.get(lang)
  if (!names) regionNames.set(lang, (names = new Intl.DisplayNames([lang], { type: 'region' })))
  try {
    return c.countryCodes.map((code) => names!.of(code.toUpperCase()) ?? code).join(' / ')
  } catch {
    return c.country
  }
}

/** Notes and process wording in the app language, falling back to what's printed on the bag. */
export function localized(c: CoffeeDraft, lang: Lang) {
  const tr = c.translations?.[lang]
  return { notes: tr?.notes.length ? tr.notes : c.notes, processDetail: tr?.processDetail || c.processDetail }
}
